class Oled:
    """Degrades to a no-op if no display is present."""

    def __init__(self, width: int = 128, height: int = 32) -> None:
        self.width = width
        self.height = height
        self.available = False
        self._bus = None
        self._buf: bytearray = bytearray()
        self._last: List[str] = []
        self._open()

    def _open(self) -> None:
        try:
            import smbus                              # type: ignore
            bus = smbus.SMBus(config.I2C_BUS)
            bus.write_byte_data(config.OLED_ADDR, 0x00, 0xAE)   # display off
            self._bus = bus
            if self.height not in (32, 64):
                self.height = 32
            self._pages = self.height // 8
            self._buf = bytearray(self.width * self._pages)
            for c in (_INIT_128x64 if self.height == 64 else _INIT_128x32):
                bus.write_byte_data(config.OLED_ADDR, 0x00, c)
            self.available = True
            self.clear()
        except Exception:
            self._bus = None
            self.available = False

    def clear(self) -> None:
        if not self.available:
            return
        self._buf = bytearray(self.width * self._pages)
        self._flush()

    def _flush(self) -> None:
        try:
            for cmd in (0x21, 0, self.width - 1, 0x22, 0, self._pages - 1):
                self._bus.write_byte_data(config.OLED_ADDR, 0x00, cmd)
            for i in range(0, len(self._buf), 16):
                self._bus.write_i2c_block_data(
                    config.OLED_ADDR, 0x40, list(self._buf[i:i + 16]))
        except Exception:
            self.available = False
            self._bus = None

    def _draw_text(self, page: int, text: str) -> None:
        x = 0
        for ch in text:
            glyph = _FONT.get(ch, _FONT.get(ch.upper(), _BLANK))
            for col in glyph:
                if x >= self.width:
                    return
                self._buf[page * self.width + x] = col
                x += 1
            if x < self.width:
                self._buf[page * self.width + x] = 0x00
                x += 1

    def _draw_bar(self, page: int, fraction: float) -> None:
        fraction = max(0.0, min(1.0, fraction))
        filled = int(self.width * fraction)
        for x in range(self.width):
            self._buf[page * self.width + x] = 0x7E if x < filled else 0x42

    def show(self, lines: List[str], bar: Optional[float] = None) -> None:
        """Render up to `pages` lines. If `bar` is given it takes the last."""
        if not self.available:
            return
        rendered = list(lines)[: self._pages]
        if rendered == self._last and bar is None:
            return
        self._last = rendered
        self._buf = bytearray(self.width * self._pages)
        for i, line in enumerate(rendered):
            self._draw_text(i, line)
        if bar is not None and self._pages > len(rendered):
            self._draw_bar(len(rendered), bar)
        elif bar is not None:
            self._draw_bar(self._pages - 1, bar)
        self._flush()

    def off(self) -> None:
        if self.available:
            try:
                self._bus.write_byte_data(config.OLED_ADDR, 0x00, 0xAE)
            except Exception:
                pass
